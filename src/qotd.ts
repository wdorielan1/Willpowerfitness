const utc = (y: number, m: number, d: number) => Date.UTC(y, m, d)
const DAY = 86400000
/** Nth weekday of a month (weekday: 0=Sun). */
const nth = (y: number, m: number, wd: number, n: number) => { const first = new Date(utc(y, m, 1)).getUTCDay(); return utc(y, m, 1 + ((wd - first + 7) % 7) + (n - 1) * 7) }
const lastWd = (y: number, m: number, wd: number) => { const last = new Date(utc(y, m + 1, 0)); return utc(y, m, last.getUTCDate() - ((last.getUTCDay() - wd + 7) % 7)) }
function easter(y: number) {
  const a = y % 19, b = Math.floor(y / 100), c = y % 100, d = Math.floor(b / 4), e = b % 4, f = Math.floor((b + 8) / 25)
  const g = Math.floor((b - f + 1) / 3), h = (19 * a + b - d - g + 15) % 30, i = Math.floor(c / 4), k = c % 4
  const l = (32 + 2 * e + 2 * i - h - k) % 7, m = Math.floor((a + 11 * h + 22 * l) / 451)
  return utc(y, Math.floor((h + l - 7 * m + 114) / 31) - 1, ((h + l - 7 * m + 114) % 31) + 1)
}
