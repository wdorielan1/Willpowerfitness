export type Season = 'winter' | 'spring' | 'summer' | 'fall'
/** month is 1 to 12. */
export const seasonOf = (month: number, day: number): Season => {
  const md = month * 100 + day
  return md >= 1221 || md < 320 ? 'winter' : md < 621 ? 'spring' : md < 922 ? 'summer' : 'fall'
}

/** First day of the season this date is in (winter starts Dec 21 of the previous year for Jan to Mar dates). */
const seasonStart = (y: number, month: number /* 1 to 12 */, day: number): number => {
  const md = month * 100 + day
  if (md >= 1221) return utc(y, 11, 21)
  if (md < 320) return utc(y - 1, 11, 21)
  if (md < 621) return utc(y, 2, 20)
  if (md < 922) return utc(y, 5, 21)
  return utc(y, 8, 22)
}

export interface DailyQuestion { q: string; theme?: string }

/** The question for a date (YYYY-MM-DD). Holidays win, then a seasonal question about once a week, otherwise evergreen. */
export function questionFor(date: string): DailyQuestion {
  const [y, m, d] = date.split('-').map(Number)
  const t = utc(y, m - 1, d)
  for (const yr of [y, y + 1]) {
    const hd = holidayDates(yr)
    for (const [id, when] of Object.entries(hd)) {
      const off = Math.round((when - t) / DAY)
      if (off >= 0 && off <= 2) return { q: HOLIDAY_QS[id].qs[off], theme: HOLIDAY_QS[id].name }
    }
  }
  const dayIndex = Math.floor(t / DAY)
  if (dayIndex % 7 === 0) {
    const s = seasonOf(m, d)
    const start = seasonStart(y, m, d)
    return { q: SEASONAL[s][Math.floor((t - start) / DAY / 7) % SEASONAL[s].length], theme: s[0].toUpperCase() + s.slice(1) }
  }
  const k = dayIndex - Math.ceil(dayIndex / 7)
  return { q: EVERGREEN[k % EVERGREEN.length] }
}
